#!/usr/bin/env python3
r"""Writes include/layout/PadTables.h from the finished pictures' anchors, and copies each pad's SWF into dist\Interface\UnbindControls.

    py -3 -I tools/gen_pad_tables.py <folder holding finished_playstation, finished_xbox, finished_steam>

The anchors come from markers projected through the camera in render_pad.py, so a table is never edited by hand: render, finish, run this.
"""
import json
import pathlib
import shutil
import sys

SRC = pathlib.Path(sys.argv[1])
REPO = pathlib.Path(__file__).resolve().parent.parent.parent  # tools/controller-layout -> the repo
OUT = REPO / "dist" / "Interface" / "UnbindControls"
OUT.mkdir(parents=True, exist_ok=True)
ORDER = ["kLT", "kLB", "kBack", "kDUp", "kDLeft", "kDDown", "kDRight", "kLStick", "kRT", "kRB", "kStart", "kY", "kB", "kA", "kX", "kRStick"]  # rows::Button's order
EXTRAS = ["LeftPad", "LeftPadUp", "LeftPadDown", "LeftPadLeft", "LeftPadRight", "RightPad", "RightPadUp", "RightPadDown", "RightPadLeft", "RightPadRight", "L4", "L5", "R4", "R5", "Touchpad"]

lines = [
    "#pragma once",
    "",
    "// GENERATED by tools/gen_pad_tables.py from the renders' projected markers: do not edit.",
    '#include "layout/LayoutRows.h"',
    "",
    "#include <array>",
    "",
    "namespace padtables",
    "{",
    "\tstruct Anchor",
    "\t{",
    "\t\tdouble x;",
    "\t\tdouble y;",
    "\t\tdouble rim;  // a leader stops this far short, on the side it comes from",
    "\t};",
    "",
    "\tstruct Pad",
    "\t{",
    "\t\tconst char* swf;  // relative to Data\\Interface",
    "\t\tdouble x, y, w, h;  // the picture, in the 1280 by 720 design",
    "\t\tstd::array<Anchor, rows::kButtonCount> at;  // by rows::Button",
    "\t\tstd::array<int, 9> left;   // the left column, top to bottom: a rows::Button, or a Part for a pad's own trackpad; -1 ends it",
    "\t\tstd::array<int, 9> right;  // the right column",
    "\t};",
    "",
    "\t// What is not one of the sixteen buttons: a trackpad, its directions and the back buttons (on the body's edge beside them).",
    "\tenum Part : int",
    "\t{",
] + [f"\t\tk{e} = {100 + i}," for i, e in enumerate(EXTRAS)] + [
    "\t};",
    "",
]
parts = {}
for name, const in (("playstation", "kPlayStation"), ("xbox", "kXbox"), ("steam", "kSteam")):
    folder = SRC / f"finished_{name}"
    data = json.load(open(folder / "anchors.json", encoding="utf-8"))
    assert data["pad"] == name
    swf = f"pad_{name}.swf"
    shutil.copyfile(folder / swf, OUT / swf)
    by_row = {row: data["anchors"][key] for key, row in data["rows"].items()}
    x, y, w, h = data["design"]
    lines.append(f'\tinline constexpr Pad {const}{{ "UnbindControls/{swf}", {x}, {y}, {w}, {h},')
    lines.append("\t\t{ { " + ", ".join("{ %s, %s, %s }" % (by_row[r]["dx"], by_row[r]["dy"], by_row[r]["dr"]) for r in ORDER) + " } },")
    def column(names):
        out = [("k" + n[5:]) if n.startswith("part:") else "rows::" + n for n in names] + ["-1"] * (9 - len(names))
        return "{ " + ", ".join(out) + " }"
    lines.append("\t\t" + column(data["left"]) + ",")
    lines.append("\t\t" + column(data["right"]) + " };")
    lines.append("")
    parts.update({k: v for k, v in data["anchors"].items() if k in EXTRAS})
lines += [f"\tinline constexpr std::array<Anchor, {len(EXTRAS)}> kParts{{ {{"]
for e in EXTRAS:
    a = parts[e]
    lines.append("\t\t{ %s, %s, 0.0 },  // %s" % (a["dx"], a["dy"], e))
lines += ["\t} };", "}", ""]
(REPO / "include" / "layout" / "PadTables.h").write_text("\n".join(lines), encoding="utf-8")
print("wrote include/layout/PadTables.h and the SWFs")
